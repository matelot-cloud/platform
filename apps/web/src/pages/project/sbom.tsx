import Badge from "@/components/ui/badge/Badge";
import { useSbom, useSbomDiff, useSbomFindings, useSboms } from "@/platform/api/hooks";
import { FindingDialog, FindingsTable } from "@/platform/components/Findings";
import { Card, EmptyState, ErrorNotice, inputClass, muted, outlineButton, SelectField, td, th, trBorder } from "@/platform/components/ui";
import { formatDate, relativeTime } from "@/platform/format";
import { useState } from "react";
import { Link, useParams } from "react-router";
import { useProject } from "./layout";


export default function SbomPage() {
  const { project } = useProject();
  const { sbomId = "" } = useParams();
  const [q, setQ] = useState("");
  const sbom = useSbom(sbomId, q || undefined);
  const others = useSboms(sbom.data?.serviceId);
  const [compare, setCompare] = useState("");
  const diff = useSbomDiff(compare || undefined, sbomId);
  const findings = useSbomFindings(sbomId);
  const [openFinding, setOpenFinding] = useState<string | null>(null);
  const s = sbom.data;
  if (sbom.error) return <ErrorNotice error={sbom.error} />;
  if (!s) return <p className={`text-sm ${muted}`}>Loading…</p>;
  const licenses = new Map<string, number>();
  for (const c of s.components) for (const l of c.licenses.length ? c.licenses : ["unknown"]) licenses.set(l, (licenses.get(l) ?? 0) + 1);
  const apiBase = "/api/v1";
  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-start justify-between gap-4">
        <div>
          <p className={`text-sm ${muted}`}><Link to={`/projects/${project.id}/inventory`} className="hover:text-brand-500">Inventory</Link> / SBOM</p>
          <h3 className="mt-1 text-lg font-semibold text-gray-800 dark:text-white/90">{s.releaseVersion ? `Release ${s.releaseVersion}` : s.targetRef} <span className={`text-sm font-normal ${muted}`}>· {s.target} · {s.componentCount} components</span></h3>
          <p className={`mt-1 text-sm ${muted}`}>{s.format.toUpperCase()} {s.specVersion ?? ""} · {s.tool ?? "unknown tool"} · {s.source === "runner" ? "generated by a platform runner" : s.source === "ci_upload" ? "uploaded by CI" : "manual"} · {s.generatedAt ? formatDate(s.generatedAt) : relativeTime(s.createdAt)}</p>
        </div>
        <a href={`${apiBase}/sboms/${s.id}/download`} className={outlineButton} target="_blank" rel="noreferrer">Download {s.format === "cyclonedx" ? "CycloneDX" : "SPDX"} JSON</a>
      </div>

      <div className="grid grid-cols-1 gap-4 md:gap-6 xl:grid-cols-3">
        <Card title="Licenses" flush>
          <ul className="divide-y divide-gray-100 dark:divide-gray-800">
            {[...licenses.entries()].sort((a, b) => b[1] - a[1]).slice(0, 12).map(([l, n]) => <li key={l} className="flex justify-between px-6 py-2 text-sm"><span className="text-gray-800 dark:text-white/90">{l}</span><span className={muted}>{n}</span></li>)}
          </ul>
        </Card>
        <Card title="Compare with another SBOM of this service" className="xl:col-span-2">
          <SelectField value={compare} onChange={setCompare} options={[{ value: "", label: "— choose the earlier version —" }, ...(others.data ?? []).filter((o) => o.id !== s.id).map((o) => ({ value: o.id, label: `${o.releaseVersion ? `Release ${o.releaseVersion}` : o.targetRef} · ${o.componentCount} components · ${relativeTime(o.createdAt)}` }))]} />
          {diff.data && (
            <div className="mt-4 grid grid-cols-1 gap-4 text-sm sm:grid-cols-3">
              <div><p className="font-medium text-success-600">Added ({diff.data.added.length})</p><ul className="mt-1 space-y-0.5">{diff.data.added.map((c) => <li key={c.id} className="text-gray-800 dark:text-white/90">{c.name} <span className={muted}>{c.version}</span></li>)}</ul></div>
              <div><p className="font-medium text-error-500">Removed ({diff.data.removed.length})</p><ul className="mt-1 space-y-0.5">{diff.data.removed.map((c) => <li key={c.id} className="text-gray-800 dark:text-white/90">{c.name} <span className={muted}>{c.version}</span></li>)}</ul></div>
              <div><p className="font-medium text-warning-600">Changed ({diff.data.changed.length})</p><ul className="mt-1 space-y-0.5">{diff.data.changed.map((c) => <li key={c.id} className="text-gray-800 dark:text-white/90">{c.name} <span className={muted}>{c.previousVersion} → {c.version}</span></li>)}</ul></div>
            </div>
          )}
          {diff.data && <p className={`mt-3 text-xs ${muted}`}>{diff.data.unchanged} components unchanged.</p>}
        </Card>
      </div>

      <Card title="Vulnerabilities" description="Open findings in the components of this SBOM (OSV, KEV, EPSS)." flush>
        <FindingsTable rows={findings.data ?? []} onOpen={setOpenFinding} showProject={false} />
      </Card>
      {openFinding && <FindingDialog findingId={openFinding} onClose={() => setOpenFinding(null)} />}

      <Card title="Components" flush actions={<input className={`${inputClass} w-64`} placeholder="Filter by name or purl" value={q} onChange={(e) => setQ(e.target.value)} aria-label="Filter components" />}>
        {s.components.length === 0 ? <EmptyState title="No components" /> : (
          <table className="min-w-full">
            <thead className="border-b border-gray-100 dark:border-gray-800"><tr><th className={th}>Component</th><th className={th}>Version</th><th className={th}>Type</th><th className={th}>Licenses</th><th className={th}>Scope</th></tr></thead>
            <tbody>
              {s.components.map((c) => (
                <tr key={c.id} className={trBorder}>
                  <td className={td}><span className="font-medium text-gray-800 dark:text-white/90">{c.namespace ? `${c.namespace}/` : ""}{c.name}</span><span className={`block font-mono text-xs ${muted}`}>{c.purl}</span></td>
                  <td className={`${td} font-mono text-sm text-gray-800 dark:text-white/90`}>{c.version ?? "—"}</td>
                  <td className={td}><Badge size="sm" color="light">{c.type}</Badge></td>
                  <td className={`${td} ${muted}`}>{c.licenses.join(", ") || "—"}</td>
                  <td className={`${td} ${muted}`}>{c.direct === null ? "—" : c.direct ? "direct" : "transitive"}</td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </Card>
    </div>
  );
}
